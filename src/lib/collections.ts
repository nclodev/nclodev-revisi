export function getCollection(letter: string) {
  return COLLECTIONS.find((c) => c.letter === letter.toLowerCase()) ?? null;
}

export const FEATURED = ["d", "c", "i", "l", "p", "a"] as const;

export function relatedCollections(letter: string, n = 3) {
  const i = COLLECTIONS.findIndex((c) => c.letter === letter.toLowerCase());
  if (i < 0) return COLLECTIONS.slice(0, n);
  const out: Collection[] = [];
  for (let k = 1; k <= COLLECTIONS.length && out.length < n; k++) {
    out.push(COLLECTIONS[(i + k) % COLLECTIONS.length]);
  }
  return out;
}
